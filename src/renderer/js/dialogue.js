export const SCENES = Object.keys(LINES);

export class Dialogue {
  constructor({ lively = false } = {}) {
    this.lively = lively;
    this._recent = new Map(); // scene → Set(最近 3 句)
  }

  setLively(v) { this.lively = Boolean(v); }

  pool(scene, tierKey) {
    const cell = LINES[scene];
    if (!cell) return [];
    let arr = cell[tierKey] || cell.friend || [];
    if (this.lively && LIVELY_LINES[scene]) {
      const extra = LIVELY_LINES[scene][tierKey] || [];
      arr = arr.concat(extra);
    }
    return arr;
  }

  // 抽一句（短期不重复：避开该场景最近 3 句；池子太小则放宽）
  pick(scene, tierKey, rand = Math.random) {
    const pool = this.pool(scene, tierKey);
    if (pool.length === 0) return null;
    const recent = this._recent.get(scene) || new Set();
    let candidates = pool.filter((l) => !recent.has(l));
    if (candidates.length === 0) candidates = pool;
    const line = candidates[Math.floor(rand() * candidates.length) % candidates.length];
    recent.add(line);
    while (recent.size > 3) {
      recent.delete(recent.values().next().value); // 淘汰最早记录
    }
    this._recent.set(scene, recent);
    return line;
  }
}
